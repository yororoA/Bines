"""Apply source changes over installed local dependencies and preserve rollback images."""
from datetime import datetime
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from common.env import load_env
from docker_launcher import BUILD_SERVICES, IMAGE_HASH_LABEL, _environment, _ps, run, source_hashes, wait_ready


def docker(*args, input=None, timeout=300):
    result = subprocess.run(["docker", *args], input=input, capture_output=True, text=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError("\n".join((result.stderr or result.stdout).splitlines()[-8:]))
    return result.stdout


def main():
    load_env()
    current = json.loads(docker("inspect", "bines-chatbot-1", "bines-qq-thinking-1"))
    # The host bridge token is generated by the running launcher. Preserve it
    # in memory while recreating services; never print it or write it to evidence.
    for entry in current[1]["Config"]["Env"]:
        key, _, value = entry.partition("=")
        if key in {"BINES_WEBSITE_BRIDGE_TOKEN"}:
            os.environ[key] = value
    uid, gid = current[0]["Config"]["User"].split(":")
    os.environ.update(BINES_UID=uid, BINES_GID=gid)
    active = int(docker("exec", "bines-chatbot-1", "python", "-c",
        "import sqlite3; db=sqlite3.connect('/app/gateway_data/gateway.db'); "
        "print(db.execute(\"SELECT COUNT(*) FROM events WHERE status IN ('pending','working')\").fetchone()[0])").strip())
    if active:
        raise RuntimeError("当前有待处理消息或执行中的批次，稍后再更新，避免中断")
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup_dir = f"/app/thingking/memory_data/backups/autonomy-{stamp}"
    for container, path, name in (
        ("bines-chatbot-1", "/app/gateway_data/gateway.db", "gateway.db"),
        ("bines-memory-server-1", "/app/thingking/memory_data/memory.db", "memory.db"),
    ):
        code = (
            "import sqlite3; from pathlib import Path; "
            f"folder=Path({backup_dir!r}); folder.mkdir(parents=True,exist_ok=True); "
            f"source=sqlite3.connect('file:'+{path!r}+'?mode=ro',uri=True); "
            f"target=sqlite3.connect(str(folder/{name!r})); source.backup(target); target.close(); source.close()"
        )
        docker("exec", container, "python", "-c", code)
    print("数据库备份完成", flush=True)

    hashes = source_hashes(_environment("chatbot"))
    rollback, prepared = {}, {}
    files = ["common/proactive.py", "common/memory_journal.py", "chatBot/proactive.py",
             "tools/context.py", "tools/activity_tool.py", "thingking/src/memory/life.py",
             "thingking/qq_thinking.py", "thingking/src/will_runtime.py"]
    expected = {path: hashlib.sha256((ROOT/path).read_bytes()).hexdigest() for path in files}
    for service, image in BUILD_SERVICES.items():
        repository = image.split(":")[0]
        rollback[service] = f"{repository}:before-autonomy-{stamp}"
        prepared[service] = f"{repository}:autonomy-{stamp}"
        docker("tag", image, rollback[service])
        dockerfile = (
            f"FROM {rollback[service]}\n"
            f"COPY --chown={uid}:{gid} . /app\n"
            f'LABEL {IMAGE_HASH_LABEL}="{hashes[service]}"\n'
        )
        docker("build", "--pull=false", "--network=none", "-f", "-", "-t", prepared[service],
               str(ROOT), input=dockerfile, timeout=900)
        code = (
            "import hashlib; from pathlib import Path; "
            f"expected={expected!r}; "
            "actual={path:hashlib.sha256((Path('/app')/path).read_bytes()).hexdigest() for path in expected}; "
            "assert actual==expected"
        )
        docker("run", "--rm", "--network", "none", "--read-only", "--entrypoint", "python",
               prepared[service], "-c", code)
        print(f"{service} 源码镜像与文件校验完成", flush=True)

    services = ("memory-server", "chatbot", "qq-thinking", "memory-worker", "rag-web")
    for service, image in BUILD_SERVICES.items():
        docker("tag", prepared[service], image)
    result = run("chatbot", "up", "-d", "--no-build", *services)
    if result.returncode:
        for service, image in BUILD_SERVICES.items():
            docker("tag", rollback[service], image)
        recovery = run("chatbot", "up", "-d", "--no-build", *services)
        raise RuntimeError(f"更新失败，已恢复原镜像标签；恢复启动结果={recovery.returncode}")
    print("服务已更新，正在检查健康状态", flush=True)
    wait_ready("chatbot")
    states = {name: {"state": row.get("State"), "health": row.get("Health")}
              for name, row in _ps("chatbot").items() if name in services}
    evidence = {"source_hashes": hashes, "file_hashes": expected, "rollback_images": rollback,
                "database_backups": str(ROOT/"thingking/memory_data/backups"/f"autonomy-{stamp}"),
                "services": states, "dependency_reinstallation": False}
    (ROOT/"verification/autonomy_deployment_result.json").write_text(
        json.dumps(evidence, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("PASS · 本地服务已更新并通过健康检查", flush=True)


if __name__ == "__main__":
    main()
